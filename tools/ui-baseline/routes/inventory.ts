import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Builds the route inventory from a pinned pip-frontend checkout: every GET route in routes.ts,
// with the guard that protects it, the parity user to capture it as, and the query parameters its
// controller reads. Routes that need data in those parameters are flagged so they can be given
// values from the seeded fixtures rather than guessed. Regenerate when the pinned commit changes.
const ROUTES_DIR = path.dirname(fileURLToPath(import.meta.url));

const GUARD_USERS: Record<string, { roles: string; user: string }> = {
  isPermittedMedia: { roles: "VERIFIED", user: "verified-media" },
  isPermittedAnyRole: { roles: "any signed-in user", user: "verified-media" },
  isPermittedAdmin: { roles: "all admin roles", user: "super-admin-local" },
  isPermittedManualUpload: { roles: "manual upload roles", user: "super-admin-local" },
  isPermittedMediaAccount: { roles: "CTSC admins", user: "super-admin-ctsc" },
  isPermittedSystemAdmin: { roles: "SYSTEM_ADMIN", user: "system-admin" }
};
// Identity-provider hand-offs: they only redirect to B2C, SSO or IDAM and never render a pip page
// (/password-change-confirmation is only reached by Azure B2C posting back after a password reset)
const AUTH_HAND_OFF =
  /^\/(login|logout|admin-login|sso-login|media-verification|cft-login|crime-login|session-expired-logout|password-change-confirmation)(\/return)?$|^\/sso\/return$|^\/sso\/logout$/;
// Pages reached part-way through a journey: opened directly they show an error or an empty
// state, because they depend on what earlier steps put in the session or form cookies
const JOURNEY_STEP =
  /-(summary|confirmation|confirmed|success|results|preview|language)$|^\/(subscription-add-list|subscription-configure-list|pending-subscriptions|remove-pending-subscription|manual-upload-summary|remove-configure-list|remove-subscription)$/;

const [pipFrontend] = process.argv.slice(2);
if (!pipFrontend) throw new Error("usage: inventory.ts <pip-frontend checkout>");

const source = await readFile(path.join(pipFrontend, "src/main/routes/routes.ts"), "utf-8");
const listLookup = JSON.parse(await readFile(path.join(pipFrontend, "src/main/resources/listLookup.json"), "utf-8")) as Record<string, { url: string }>;
// Some deprecated list types have an empty url, which would otherwise make the home page a list page
const listUrls = new Set(
  Object.values(listLookup)
    .filter((listType) => listType.url)
    .map((listType) => `/${listType.url}`)
);
const controllerFiles = await indexControllers(path.join(pipFrontend, "src/main/controllers"));

const routes = [];
for (const declaration of routeDeclarations(source)) {
  const guard = Object.keys(GUARD_USERS).find((name) => new RegExp(`\\b${name}\\b`).test(declaration.body));
  const controller = declaration.body.match(/cradle\.(\w+)Controller/)?.[1] ?? null;
  const queryParams = controller
    ? await controllerQueryParams(controller)
    : [...new Set([...declaration.body.matchAll(/req\.query\??\.(\w+)/g)].map((m) => m[1]))];

  const category = listUrls.has(declaration.path)
    ? "list-page"
    : AUTH_HAND_OFF.test(declaration.path) || /passport\.authenticate/.test(declaration.body)
      ? "auth-hand-off"
      : declaration.path.includes("*")
        ? "middleware"
        : JOURNEY_STEP.test(declaration.path)
          ? "journey-step"
          : guard
            ? "signed-in"
            : "public";

  routes.push({
    path: declaration.path,
    category,
    guard: guard ?? null,
    roles: guard ? GUARD_USERS[guard].roles : null,
    captureAs: guard ? GUARD_USERS[guard].user : null,
    controller,
    queryParams,
    needsData: queryParams.length > 0
  });
}

const counts = Object.fromEntries(
  Object.entries(Object.groupBy(routes, (route) => route.category)).map(([category, inCategory]) => [category, inCategory?.length ?? 0])
);
await writeFile(
  path.join(ROUTES_DIR, "pip-routes.json"),
  `${JSON.stringify({ $comment: "Generated by inventory.ts from pip-frontend routes.ts; do not edit by hand.", counts, routes }, null, 2)}\n`
);
console.log(`${routes.length} GET routes`, counts);

function routeDeclarations(text: string): { path: string; body: string }[] {
  const starts = [...text.matchAll(/app\.get\(\s*['"]([^'"]+)['"]/g)];
  return starts.map((match, i) => ({
    path: match[1],
    body: text.slice(match.index, starts[i + 1]?.index ?? text.length).split(/\n\s*app\.(post|use|put|delete)\(/)[0]
  }));
}

async function indexControllers(dir: string): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  for (const entry of await readdir(dir, { withFileTypes: true, recursive: true })) {
    if (entry.isFile() && entry.name.endsWith("Controller.ts")) {
      const name = entry.name.replace(/Controller\.ts$/, "");
      files.set(name.charAt(0).toLowerCase() + name.slice(1), path.join(entry.parentPath, entry.name));
    }
  }
  return files;
}

async function controllerQueryParams(controller: string): Promise<string[]> {
  const file = controllerFiles.get(controller);
  if (!file) return [];
  const text = await readFile(file, "utf-8");
  const direct = [...text.matchAll(/req\.query\??\.(\w+)/g)].map((match) => match[1]);
  const bracketed = [...text.matchAll(/req\.query\??\.?\[['"](\w+)['"]\]/g)].map((match) => match[1]);
  const destructured = [...text.matchAll(/\{([^}]+)\}\s*=\s*req\.query/g)].flatMap((match) => match[1].split(",").map((name) => name.split(":")[0].trim()));
  return [...new Set([...direct, ...bracketed, ...destructured])].filter(Boolean);
}
