import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Proposes which CaTH page corresponds to each pip page and journey step. Same path is taken as a
// match; otherwise the closest CaTH route by name is suggested for a human to confirm. Entries a
// human has already reviewed in route-map.json are kept as they are when this is re-run.
const ROUTES_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_DIR = path.join(ROUTES_DIR, "../../..");
// Every directory apps/web/src/app.ts hands to createSimpleRouter for pages
const PAGE_ROOTS = [path.join(REPO_DIR, "apps/web/src/pages"), path.join(REPO_DIR, "libs/system-admin-pages/src/pages")];
const OUTPUT = path.join(ROUTES_DIR, "route-map.json");
const SUGGESTION_THRESHOLD = 0.5;

// Word-level renames seen between pip's and CaTH's route names
const SYNONYMS: Record<string, string> = {
  view: "explorer",
  viewer: "list",
  details: "detail",
  confirmed: "success",
  confirmation: "confirm",
  number: "",
  manage: "",
  subscribers: "subscriber",
  users: "user",
  publications: "publication",
  locations: "location",
  accounts: "account",
  applications: "application",
  subscriptions: "subscription"
};

const inventory = JSON.parse(await readFile(path.join(ROUTES_DIR, "pip-routes.json"), "utf-8")) as { routes: PipRoute[] };
const pipRoutes = inventory.routes.filter((route) => ["public", "signed-in", "journey-step"].includes(route.category));
const cathRoutes = await cathRouteList();
const pipHeadings = await pipHeadingsByRoute(process.argv[2]);
const reviewed = new Map(
  existsSync(OUTPUT) ? (JSON.parse(await readFile(OUTPUT, "utf-8")).routes as MapEntry[]).filter((e) => e.reviewed).map((e) => [e.pip, e]) : []
);

const routes: MapEntry[] = pipRoutes.map((pip) => {
  const kept = reviewed.get(pip.path);
  if (kept) return kept;
  const same = cathRoutes.find((cath) => cath.path === pip.path);
  if (same) return entry(pip, same, "same-path", 1);
  // The page heading is the stronger signal: route names were often changed, page titles rarely
  const heading = pipHeadings.get(pip.path);
  const ranked = cathRoutes
    .map((cath) => ({ cath, score: Math.max(similarity(pip.path, cath.path), heading && cath.title ? textSimilarity(heading, cath.title) : 0) }))
    .sort((a, b) => b.score - a.score);
  const best = ranked[0];
  if (best && best.score >= SUGGESTION_THRESHOLD) {
    // Identical headings make a suggestion near-certain; a name-only or partial match needs a human
    const sameHeading = Boolean(heading && best.cath.title && normaliseHeading(heading) === normaliseHeading(best.cath.title));
    return {
      ...entry(pip, best.cath, "suggested", best.score),
      confidence: sameHeading ? "high" : "low",
      alternatives: ranked
        .slice(1, 3)
        .filter((r) => r.score >= SUGGESTION_THRESHOLD)
        .map((r) => r.cath.path)
    };
  }
  return entry(pip, null, "unmapped", best?.score ?? 0);
});

const counts = routes.reduce<Record<string, number>>((acc, e) => {
  const key = e.match === "suggested" ? `suggested-${e.confidence}` : e.match;
  acc[key] = (acc[key] ?? 0) + 1;
  return acc;
}, {});
const mappedCath = new Set(routes.map((e) => e.cath).filter(Boolean));
const cathOnly = cathRoutes.filter((cath) => !mappedCath.has(cath.path)).map((cath) => cath.path);
await writeFile(
  OUTPUT,
  `${JSON.stringify(
    {
      $comment:
        "pip page or journey step -> CaTH page. Generated by route-map.ts; set reviewed: true (and correct cath) on entries you have checked, and re-running keeps them. same-path matches are by URL; suggested ones are by name and need a human. cath: null means CaTH has no equivalent yet.",
      counts,
      routes,
      cathOnly
    },
    null,
    2
  )}\n`
);
console.log(`${routes.length} pip routes:`, counts, `· ${cathOnly.length} CaTH routes with no pip counterpart`);

function entry(pip: PipRoute, cath: CathRoute | null, match: MapEntry["match"], score: number): MapEntry {
  return {
    pip: pip.path,
    pipHeading: pipHeadings.get(pip.path) ?? null,
    pipCategory: pip.category,
    pipRole: pip.captureAs,
    cath: cath?.path ?? null,
    cathTitle: cath?.title ?? null,
    cathRoles: cath?.roles ?? null,
    match,
    score: Math.round(score * 100) / 100,
    reviewed: false
  };
}

// Pages are folders with an index.ts, or [param].ts files; (group) folders do not appear in the URL
async function cathRouteList(): Promise<CathRoute[]> {
  const found: CathRoute[] = [];
  const toPath = (relative: string) =>
    `/${relative
      .split(path.sep)
      .filter((part) => !/^\(.*\)$/.test(part))
      .join("/")}`;
  const describe = async (controller: string, contentDir: string) => {
    const source = await readFile(controller, "utf-8");
    const roles = [...new Set([...source.matchAll(/USER_ROLES\.([A-Z_]+)/g)].map((m) => m[1]))];
    return { roles, title: await pageTitle(path.join(contentDir, "en.ts")) };
  };
  const walk = async (dir: string, root: string): Promise<void> => {
    for (const item of await readdir(dir, { withFileTypes: true })) {
      const full = path.join(dir, item.name);
      if (item.isDirectory()) {
        if (existsSync(path.join(full, "index.ts")))
          found.push({ path: toPath(path.relative(root, full)), ...(await describe(path.join(full, "index.ts"), full)) });
        await walk(full, root);
      } else if (/^\[[^\]]+\]\.ts$/.test(item.name)) {
        found.push({ path: toPath(path.relative(root, full).replace(/\.ts$/, "")), ...(await describe(full, dir)) });
      }
    }
  };
  for (const root of PAGE_ROOTS) {
    if (existsSync(path.join(root, "index.ts"))) found.push({ path: "/", ...(await describe(path.join(root, "index.ts"), root)) });
    await walk(root, root);
  }
  return found;
}

// The page's own title from its English content, preferring the most specific key
async function pageTitle(file: string): Promise<string | null> {
  if (!existsSync(file)) return null;
  const source = await readFile(file, "utf-8");
  for (const key of ["pageTitle", "title", "header", "heading"]) {
    const match = source.match(new RegExp(`^\\s*${key}\\s*:\\s*["'\`]([^"'\`]+)["'\`]`, "m"));
    if (match) return match[1];
  }
  return null;
}

// Headings pip shows on each route, from a baseline run's page captures and journey steps
async function pipHeadingsByRoute(runDir: string | undefined): Promise<Map<string, string>> {
  const headings = new Map<string, string>();
  if (!runDir) return headings;
  const pagesIndex = path.join(runDir, "pages/index.jsonl");
  if (existsSync(pagesIndex)) {
    for (const line of (await readFile(pagesIndex, "utf-8")).trim().split("\n")) {
      const entry = JSON.parse(line);
      if (entry.locale !== "en" || entry.state !== "default") continue;
      const meta = JSON.parse(await readFile(path.join(runDir, "pages", entry.id, "en/default/meta.json"), "utf-8"));
      if (meta.h1?.[0]) headings.set(entry.source.route, meta.h1[0]);
    }
  }
  const journeysDir = path.join(runDir, "journeys");
  if (existsSync(journeysDir)) {
    for (const journey of await readdir(journeysDir)) {
      const file = path.join(journeysDir, journey, "en/journey.json");
      if (!existsSync(file)) continue;
      for (const step of JSON.parse(await readFile(file, "utf-8")).steps) {
        const heading = step.h1?.find((h: string) => h && !/^(warning|there is a problem)$/i.test(h));
        if (heading && !headings.has(step.path)) headings.set(step.path, heading);
      }
    }
  }
  return headings;
}

function normaliseHeading(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

function textSimilarity(a: string, b: string): number {
  const words = (text: string) =>
    new Set(
      text
        .toLowerCase()
        .replace(/[^\p{L}\p{N}\s]/gu, " ")
        .split(/\s+/)
        .filter((w) => w.length > 2)
    );
  const wa = words(a);
  const wb = words(b);
  if (!wa.size || !wb.size) return 0;
  return [...wa].filter((w) => wb.has(w)).length / Math.max(wa.size, wb.size);
}

// Share of route words in common after renames, so "audit-log-viewer" finds "audit-log-list"
function similarity(a: string, b: string): number {
  const words = (route: string) =>
    new Set(
      route
        .split(/[/-]/)
        .filter(Boolean)
        .map((word) => SYNONYMS[word] ?? word)
        .filter(Boolean)
    );
  const wa = words(a);
  const wb = words(b);
  if (!wa.size || !wb.size) return 0;
  return [...wa].filter((w) => wb.has(w)).length / Math.max(wa.size, wb.size);
}

interface PipRoute {
  path: string;
  category: string;
  captureAs: string | null;
}

interface CathRoute {
  path: string;
  roles: string[];
  title: string | null;
}

interface MapEntry {
  pip: string;
  pipHeading: string | null;
  cathTitle: string | null;
  pipCategory: string;
  pipRole: string | null;
  cath: string | null;
  cathRoles: string[] | null;
  match: "same-path" | "suggested" | "unmapped";
  score: number;
  reviewed: boolean;
  confidence?: "high" | "low";
  alternatives?: string[];
}
